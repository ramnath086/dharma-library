def emit_names(em, kind, table, ent):
    for lang, name in (ent.get("names") or {}).items():
        script = {"en": "Latn", "ml": "Mlym", "hi": "Deva", "sa": "Deva", "kn": "Knda", "te": "Telu", "ta": "Taml", "bn": "Beng", "gu": "Gujr"}[lang]
        em.add(f"""
insert into entity_names (entity_kind, entity_id, language_code, script_code, name, is_primary)
values ({q(kind)}::entity_kind, (select id from {table} where slug={q(ent['slug'])}), {q(lang)}, {q(script)}, {q(name)}, true)
on conflict (entity_kind, entity_id, language_code, script_code, name) do nothing""")
    # IAST + Devanagari names from the entity itself
    for lang, script, key in (("sa", "Latn", "name_iast"), ("sa", "Deva", "name_sa"), ("sa", "Latn", "title_iast"), ("sa", "Deva", "title_sa")):
        if ent.get(key):
            em.add(f"""
insert into entity_names (entity_kind, entity_id, language_code, script_code, name, is_primary)
values ({q(kind)}::entity_kind, (select id from {table} where slug={q(ent['slug'])}), {q(lang)}, {q(script)}, {q(ent[key])}, true)
on conflict (entity_kind, entity_id, language_code, script_code, name) do nothing""")


def emit_content(em, work_slug, ref, edition_slug, body, notes=None, word_meanings=None):
    em.add(f"""
insert into verse_contents (verse_id, edition_id, body, word_meanings, notes, status)
values ((select id from verses where ref={q(ref)} and work_id=(select id from works where slug={q(work_slug)})), (select id from editions where slug={q(edition_slug)}),
        {q(body)}, {jq(word_meanings) if word_meanings else 'null'}, {q(notes)}, 'published')
on conflict (verse_id, edition_id) do update set body=excluded.body, word_meanings=excluded.word_meanings, notes=excluded.notes, status='published'""")


