def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--db", help="postgres URI (default: local pgserver)")
    a = ap.parse_args()

    OUT.mkdir(parents=True, exist_ok=True)
    for wj in sorted(glob.glob(str(CONTENT / "*" / "work.json"))):
        wd = pathlib.Path(wj).parent
        em = Emitter(wd.name)
        em.add(HELPERS)
        print("== ingest", wd.name)
        ingest_work(wd, em)
        outp = OUT / f"{wd.name}.sql"
        outp.write_text(em.dump(), encoding="utf-8")
        print("   wrote", outp.relative_to(ROOT))
        if a.apply:
            uri = a.db
            if not uri:
                sys.path.insert(0, str(ROOT / "scripts"))
                import localdb  # type: ignore
                uri = localdb.db_uri(localdb.server())
                psql = localdb.psql_bin()
            else:
                psql = "psql"
            r = subprocess.run([psql, uri, "-v", "ON_ERROR_STOP=1", "-q", "-f", str(outp)], capture_output=True, text=True)
            if r.returncode != 0:
                print(r.stderr)
                raise SystemExit("apply failed")
            print("   applied")


if __name__ == "__main__":
    main()
